export type UiMessage = string | {
  type: 'translation'
  key: MessageKey
  values?: Record<string, string | number | UiMessage>
} | {
  type: 'api-error'
  code: string | null
  fallback: MessageKey
  detail: string | null
} | {
  type: 'task-error'
  taskKind: string
  status: string
  detail: string | null
}

export type TaskErrorContext = {
  kind: string
  status?: string | null
}

const historicalTaskErrorKeys: Record<string, MessageKey> = {
  questions: 'error.questionsGeneration',
  diagnosis: 'error.diagnosis',
  diagnosis_report: 'error.diagnosisSummary',
  monitoring: 'monitoring.failure',
  article_titles: 'error.articles',
  article_body: 'error.aiTask',
  content_audit: 'content.failure',
}

function interpolate(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => String(values[key] ?? `{${key}}`))
}

export function translate(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const template = messages[locale][key] ?? messages['zh-CN'][key] ?? key
  return interpolate(template, values)
}

export function uiMessage(key: MessageKey, values?: Record<string, string | number | UiMessage>): UiMessage {
  return { type: 'translation', key, ...(values ? { values } : {}) }
}

function apiErrorParts(cause: unknown): { code: string | null; detail: string | null } {
  const record = cause && typeof cause === 'object' ? cause as { code?: unknown; message?: unknown } : null
  return {
    code: typeof record?.code === 'string' && record.code.trim() ? record.code : null,
    detail: typeof record?.message === 'string' && record.message.trim() ? record.message : null,
  }
}

export function apiErrorMessage(cause: unknown, fallback: MessageKey): UiMessage {
  const { code, detail } = apiErrorParts(cause)
  return { type: 'api-error', code, fallback, detail }
}

export function taskErrorMessage(taskKind: string, status: string, detail: string | null | undefined): UiMessage {
  return { type: 'task-error', taskKind, status, detail: typeof detail === 'string' && detail.trim() ? detail : null }
}

function originalErrorDetail(detail: string, locale: Locale): string {
  return translate(locale, 'error.originalDetail', { detail })
}

function localizedApiErrorParts(
  code: string | null,
  detail: string | null,
  locale: Locale,
  fallback: MessageKey,
): string {
  // A stable API code is the source for the localized title.  Operation-level
  // envelopes also retain a non-canonical server detail explicitly labelled;
  // guessing from a Chinese prefix could otherwise hide useful diagnostics.
  const key = code ? serverErrorCodeKeys[code] : undefined
  if (key) {
    if (!detail) return translate(locale, key)
    const canonicalDetail = messages['zh-CN'][key]
    const fallbackDetail = messages['zh-CN'][fallback]
    const keepOriginal = code !== null && serverErrorCodesWithOriginalDetail.has(code)
      && detail !== canonicalDetail
      && detail !== fallbackDetail
    return keepOriginal ? `${translate(locale, key)} ${originalErrorDetail(detail, locale)}` : translate(locale, key)
  }
  const generic = translate(locale, fallback)
  return detail ? `${generic} ${originalErrorDetail(detail, locale)}` : generic
}

export function browserLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en'
  try {
    const candidate = navigator.languages?.[0] || navigator.language || ''
    return /^zh(?:[-_]|$)/i.test(candidate) ? 'zh-CN' : 'en'
  } catch {
    return 'en'
  }
}

export function resolveLocale(preference: LocalePreference, browser: Locale = browserLocale()): Locale {
  return preference === 'auto' ? browser : preference
}

export function applyDocumentLocale(locale: Locale): void {
  if (typeof document !== 'undefined') document.documentElement.lang = locale
}

export function localizeServerMessage(message: string | null | undefined, locale: Locale, task?: TaskErrorContext): string {
  const raw = typeof message === 'string' ? message : ''
  const detail = raw.trim() ? raw : null
  if (!task || task.status !== 'failed') return raw
  const generic = translate(locale, historicalTaskErrorKeys[task.kind] ?? 'error.aiTask')
  return detail ? `${generic} ${originalErrorDetail(detail, locale)}` : generic
}

export function localizeApiError(
  cause: unknown,
  locale: Locale,
  fallback: MessageKey,
): string {
  const { code, detail } = apiErrorParts(cause)
  return localizedApiErrorParts(code, detail, locale, fallback)
}

function resolveUiMessageValue(value: string | number | UiMessage, locale: Locale): string | number {
  return typeof value === 'object' ? resolveUiMessage(value, locale) : value
}

export function resolveUiMessage(message: UiMessage | null | undefined, locale: Locale): string {
  if (message === null || message === undefined) return ''
  if (typeof message === 'string') return message
  if (message.type === 'translation') {
    const values = message.values
      ? Object.fromEntries(Object.entries(message.values).map(([key, value]) => [key, resolveUiMessageValue(value, locale)]))
      : undefined
    return translate(locale, message.key, values)
  }
  if (message.type === 'api-error') return localizedApiErrorParts(message.code, message.detail, locale, message.fallback)
  return localizeServerMessage(message.detail, locale, { kind: message.taskKind, status: message.status })
}

export function readLocalePreference(storage: Storage | null | undefined): LocalePreference {
  try {
    const value = storage?.getItem(STORAGE_KEY)
    return value === 'zh-CN' || value === 'en' || value === 'auto' ? value : 'auto'
  } catch {
    return 'auto'
  }
}

export function persistLocalePreference(storage: Storage | null | undefined, preference: LocalePreference): void {
  try {
    storage?.setItem(STORAGE_KEY, preference)
  } catch {
    // Storage is optional. A blocked or full localStorage must not break UI.
  }
}

function browserStorage(): Storage | null {
  if (typeof window === 'undefined') return null
  try {
    return window.localStorage
  } catch {
    return null
  }
}

export function localeName(locale: Locale): string {
  return locale === 'zh-CN' ? '简体中文' : 'English'
}

type I18nContextValue = {
  locale: Locale
  preference: LocalePreference
  setPreference: (preference: LocalePreference) => void
  t: (key: MessageKey, values?: Record<string, string | number>) => string
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string
  formatPercent: (value: number | null) => string
  formatDate: (value: string | null, options?: Intl.DateTimeFormatOptions) => string
}

const defaultContext: I18nContextValue = {
  locale: 'zh-CN',
  preference: 'auto',
  setPreference: () => undefined,
  t: (key, values) => translate('zh-CN', key, values),
  formatNumber: (value, options) => new Intl.NumberFormat('zh-CN', options).format(value),
  formatPercent: (value) => value === null ? '—' : `${Math.round(value * 100)}%（${Math.round(value * QUESTION_TOTAL)} / ${QUESTION_TOTAL}）`,
  formatDate: (value, options = { year: 'numeric', month: '2-digit', day: '2-digit' }) => value ? new Intl.DateTimeFormat('zh-CN', options).format(new Date(value)) : '—',
}

const I18nContext = createContext<I18nContextValue>(defaultContext)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [preference, setPreferenceState] = useState<LocalePreference>(() => (
    readLocalePreference(browserStorage())
  ))
  const [browser, setBrowser] = useState<Locale>(() => browserLocale())
  const locale = resolveLocale(preference, browser)

  const setPreference = useCallback((next: LocalePreference) => {
    setPreferenceState(next)
    if (next === 'auto') setBrowser(browserLocale())
    persistLocalePreference(browserStorage(), next)
  }, [])

  useEffect(() => {
    applyDocumentLocale(locale)
  }, [locale])

  useEffect(() => {
    if (typeof window === 'undefined') return
    const onLanguageChange = () => setBrowser(browserLocale())
    window.addEventListener('languagechange', onLanguageChange)
    return () => window.removeEventListener('languagechange', onLanguageChange)
  }, [])

  const t = useCallback((key: MessageKey, values?: Record<string, string | number>) => translate(locale, key, values), [locale])
  const formatNumber = useCallback((value: number, options?: Intl.NumberFormatOptions) => new Intl.NumberFormat(locale, options).format(value), [locale])
  const formatPercent = useCallback((value: number | null) => value === null ? '—' : `${Math.round(value * 100)}% (${Math.round(value * QUESTION_TOTAL)} / ${QUESTION_TOTAL})`, [])
  const formatDate = useCallback((value: string | null, options: Intl.DateTimeFormatOptions = { year: 'numeric', month: '2-digit', day: '2-digit' }) => {
    if (!value) return '—'
    const date = new Date(value)
    return Number.isNaN(date.getTime()) ? '—' : new Intl.DateTimeFormat(locale, options).format(date)
  }, [locale])

  const context = useMemo(() => ({ locale, preference, setPreference, t, formatNumber, formatPercent, formatDate }), [formatDate, formatNumber, formatPercent, locale, preference, setPreference, t])
  return <I18nContext.Provider value={context}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}
