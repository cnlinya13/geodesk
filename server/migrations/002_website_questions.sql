  ADD COLUMN IF NOT EXISTS website_pages_succeeded INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS website_pages_failed INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS questions_generation_status TEXT NOT NULL DEFAULT 'not_started',
  ADD COLUMN IF NOT EXISTS questions_generation_started_at TIMESTAMPTZ,
