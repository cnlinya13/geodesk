BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'geo_projects_website_crawl_status_check') THEN
    ALTER TABLE geo_projects ADD CONSTRAINT geo_projects_website_crawl_status_check
      CHECK (website_crawl_status IN ('not_started', 'crawling', 'completed', 'failed'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'geo_projects_questions_generation_status_check') THEN
    ALTER TABLE geo_projects ADD CONSTRAINT geo_projects_questions_generation_status_check
      CHECK (questions_generation_status IN ('not_started', 'generating', 'completed', 'failed'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'geo_projects_website_page_counts_check') THEN
    ALTER TABLE geo_projects ADD CONSTRAINT geo_projects_website_page_counts_check
